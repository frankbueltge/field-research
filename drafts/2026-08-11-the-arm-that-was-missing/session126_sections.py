def _splice(path, tag, block, write):
    text = open(path).read()
    b, e = begin(tag), end(tag)
    if b in text and e in text:
        head, rest = text.split(b, 1)
        _, tail = rest.split(e, 1)
        new = head + block + tail
        current = b + rest.split(e, 1)[0] + e
    else:
        new = text.rstrip("\n") + "\n\n" + block + "\n"
        current = None
    if write:
        open(path, "w").write(new)
    return current


def main(argv):
    mode = argv[0] if argv else "--check"
    if mode not in ("--check", "--write"):
        raise SystemExit("usage: session126_sections.py [--check|--write]")
    write = mode == "--write"

    if write:
        copied = copy_sidecars()
        rep = repair_confirmation_hash(apply=True)
        print("sidecars copied into the bundle: " + (", ".join(copied) or "none (already current)"))
        print("confirmation-record corrections_sha256: "
              + ("repaired -> " + rep["sha256"] if rep["changed"] else "already current"))

    blocks, fx, fp = render_blocks()
    ok = True
    for path, tag in BLOCKS.items():
        current = _splice(path, tag, blocks[path], write)
        if not write:
            if current is None:
                print("FAIL: " + path + " has no SESSION-126:" + tag + " block", file=sys.stderr)
                ok = False
            elif current.strip() != blocks[path].strip():
                print("FAIL: the SESSION-126:" + tag + " block in " + path
                      + " is not what the data says now.", file=sys.stderr)
                ok = False
        else:
            print("wrote SESSION-126:" + tag + " into " + path)

    if write:
        for table, inst in ((PROV, fx), (PROV_FIGURES, fp)):
            prov = json.load(open(table))
            # idempotent: this session's entries are replaced, never stacked, so re-running
            # --write cannot inflate n_figures.
            prov["figures"] = [f for f in prov["figures"]
                               if not f.get("note", "").startswith(MARK)]
            added = []
            for f in inst.provenance()["figures"]:
                f["note"] = MARK + ("; " + f["note"] if f["note"] else "")
                added.append(f)
            prov["figures"].extend(added)
            prov["n_figures"] = len(prov["figures"])
            json.dump(prov, open(table, "w"), indent=1)
            print("provenance: " + str(len(added)) + " figures into "
                  + os.path.basename(table) + "; n_figures is now " + str(prov["n_figures"]))
        return 0

    if ok:
        print("session-126 sections: OK - both blocks match what their data says now")
        return 0
    print("Run --write and read the diff.", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
