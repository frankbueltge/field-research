        "the honest statement of this panel's date, and it travels with any reuse of an age-band "
        "cell, an age-gradient row or an expectation figure.",
        "",
        "**And a confound is open that this bracket does not close.** Encyclopedia editions prune "
        "and archive-fix dead citations, and they do so at rates that are themselves a function of "
