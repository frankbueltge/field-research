    n_meas = fp.n(pe, "n_absent_on_every_day_measured")
    p_meas = fp.pct(pe, "frac_absent_on_every_day_measured", dp=2)
    n_ind = fp.n(pe, "n_never_retrievable_but_broken_only_by_indeterminate")
    n_multi = fp.n(pe, "n_units_with_more_than_one_determinate_state")

