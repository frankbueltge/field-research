        begin("PERSISTENCE"),
        "",
        "## How stable an absence is, across the whole panel",
        "",
        "*Added " + fp.lit("2026-08-18", "the date this section was added") + ". Found by the adversary at the gauntlet of " + fp.lit("2026-08-17", "the date of the sixth gauntlet, at which this result was raised") + ", in this "
        "practice's own series file, which had sat in this repository for six days without anyone "
