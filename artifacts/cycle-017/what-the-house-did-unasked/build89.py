#!/usr/bin/env python3
"""Reading 89 (state 5, session 287): writes data89.js for the page from join89.json, agree89.json, heirs89.json and
results87.json. Standard library only. Run after join89.py, agree89.py and heirs89.py."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
J = lambda f: json.load(open(os.path.join(HERE, f), encoding='utf-8'))
jn, ag, r87, hr = J('join89.json'), J('agree89.json'), J('results87.json'), J('heirs89.json')
HR = {(h['row'], h['deed']): h for h in hr['heirs']}
ARCH = lambda t: t.replace("Frank's", "the architect's").replace('Frank', 'the architect')
D87 = {(int(d['row']), int(d['n'])): d for d in r87['deeds']}
CR = {(d['row'], d['deed']): d for d in J('credit88.json')['deeds']}
pairs = []
for p in jn['pairs']:
    d = D87[(p['row'], p['deed'])]
    pairs.append({'row': p['row'], 'deed': p['deed'], 'log_line': p['log_line'], 'date': d['date'],
                  'kind': d['kind'], 'deed_line': ARCH(d['deed_line']), 'repo': p['repair_repo'], 'repair': p['repair'],
                  'deed_repos': p['deed_repos'],
                  'deed_commits': [[c['repo'], c['hash']] for c in CR[(p['row'], p['deed'])]['deed_commits'] if c], 'code': p['code'], 'cls': p['class'], 'lines': p['lines'],
                  'taken': p.get('lines_taken_out'), 'name': p['name'], 'file': p['file'],
                  'points': p.get('git_points'), 'heirs': p.get('heirs_before'),
                  'heir1': (p.get('heirs_before_hashes') or [None])[0], 'unread': len(p['unread_paths']),
                  'heir_h': HR.get((p['row'], p['deed']), {}).get('hours_after_deed'),
                  'heir_sig': HR.get((p['row'], p['deed']), {}).get('signer'),
                  'named_hash': p['name'] and p['code'] != 'same_commit',
                  'atelier': ag['by_pair'].get(f"{p['row']}|{p['deed']}")})
data = {'reading': 89, 'session': 287, 'built': '2026-11-21', 'res': jn['results'], 'agree': ag['results'],
        'heirs': hr['results'],
        'pairs': pairs}
with open(os.path.join(HERE, 'data89.js'), 'w', encoding='utf-8') as f:
    f.write('// generated by build89.py from join89.json, agree89.json, heirs89.json and results87.json\n')
    f.write('window.DATA89=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('pairs', len(pairs))
